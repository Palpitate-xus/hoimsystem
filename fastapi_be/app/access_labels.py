def permission_label(module, method, path, function):
    """Use explicit business objects and verbs without changing authorization."""
    explicit = ENDPOINT_LABELS.get((method, path))
    if explicit:
        return explicit
    parts = path.rstrip("/").split("/")
    tail = parts[-1]
    resource = next((RESOURCE_LABELS[part] for part in reversed(parts) if part in RESOURCE_LABELS), MODULE_LABELS.get(module, "业务资料"))
    if tail == "audit":
        return "查看审计记录" if method == "GET" else "审核" + resource
    if tail == "review" and method == "GET":
        return "查看复核记录：" + resource
    if tail == "catalog":
        return "查看" + resource + "目录"
    action = ACTION_LABELS.get(tail)
    if action:
        return action + "：" + resource
    if method == "GET" and "{" in tail:
        return "查看" + resource + "详情"
    # Source routers sometimes prefix helpers with admin_; use the actual verb.
    words = function.split("_")
    if words[0] == "admin" and len(words) > 1:
        words = words[1:]
    verb = next((FUNCTION_ACTIONS[word] for word in words if word in FUNCTION_ACTIONS), None)
    if method == "GET" and verb in {"审核", "复核"}:
        return "查看复核记录：" + resource
    if verb:
        return verb + "：" + resource
    if method == "GET":
        return "查看" + resource
    if method in {"PUT", "PATCH"}:
        return "修改" + resource
    if method == "DELETE":
        return "删除" + resource
    return "提交" + resource + "请求"
