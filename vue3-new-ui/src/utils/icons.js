const normalize = name => name.replace(/[\s_-]/g, "").toLowerCase();
const registry = new Map(Object.entries(components).map(([name, component]) => [normalize(name), component]));
for (const [alias, name] of Object.entries(aliases)) {
  const key = normalize(alias);
  if (!registry.has(key)) registry.set(key, components[name]);
}

export function resolveIcon(icon) {
  const name = Array.isArray(icon) ? icon[1] : icon;
  return typeof name === "string" ? registry.get(normalize(name)) || QuestionFilled : QuestionFilled;
}
